Task 1 – EDA on Retail Sales Data

1. Project Overview
This project performs Exploratory Data Analysis (EDA) on a retail sales dataset.
The purpose of the analysis is to understand sales performance, customer demographics, category performance, revenue, costs and profitability.
Python-based data analysis and visualization techniques are used to convert the raw retail transaction data into meaningful business insights.

2. Objectives
The main objectives of this project are:
Understand the structure and quality of the retail sales dataset.
Check and clean the data.
Calculate descriptive statistics.
Analyze monthly sales trends.
Analyze quarterly sales trends.
Analyze customer demographics.
Analyze sales performance by category.
Analyze revenue and quantity sold by category.
Analyze profitability using sales and COGS.
Study relationships between numerical variables.
Create meaningful visualizations.
Generate business recommendations from the analysis.


